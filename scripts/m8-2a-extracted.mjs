/**
 * M8.2A extracted shop rows from the three owner screenshots.
 * Original spelling preserved. Tom/Liju/Arun are not assigned.
 * Same name on two geographic routes stays two shops.
 */
export function normalizeShopName(raw) {
  return String(raw ?? "")
    .replace(/\u00a0/g, " ")
    .trim()
    .replace(/[ \t]+/g, " ")
}

export function proposedShopKey(routeCode, originalShopName) {
  return `${normalizeShopName(routeCode).toLowerCase()}::${normalizeShopName(originalShopName).toLowerCase()}`
}

function rows(routeCode, weekday, sourceSheet, names, notes = {}) {
  return names.map((name, index) => {
    const original = normalizeShopName(name)
    const seq = index + 1
    const extra = notes[seq] || {}
    return {
      source_sheet: sourceSheet,
      route_code: routeCode,
      weekday,
      sequence: seq,
      original_shop_name: original,
      normalized_shop_name: original,
      proposed_shop_key: proposedShopKey(routeCode, original),
      review_status: extra.review_status || "extracted",
      review_notes: extra.review_notes || "",
    }
  })
}

